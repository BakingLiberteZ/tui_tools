def get_modal_message(context: str) -> str:
    """
    Get a random fun message for a modal context.

    Args:
        context: The modal type (backup, delete, send_amount, etc.)

    Returns:
        A random message string for that context
    """
    messages_map = {
        "backup": BACKUP_MESSAGES,
        "delete": DELETE_MESSAGES,
        "send_amount": SEND_AMOUNT_MESSAGES,
        "send_passphrase": SEND_PASSPHRASE_MESSAGES,
        "confirm": CONFIRM_MESSAGES,
        "network": NETWORK_MESSAGES,
        "wallet_name": WALLET_NAME_MESSAGES,
        "secret_key": SECRET_KEY_MESSAGES,
        "address": ADDRESS_MESSAGES,
        "passphrase": PASSPHRASE_PROMPT_MESSAGES,
        "address_detail": ADDRESS_DETAIL_MESSAGES,
        "import": IMPORT_MESSAGES,
        "delegate": DELEGATE_MESSAGES,
        "stake": STAKE_MESSAGES,
        "already_staking": ALREADY_STAKING_MESSAGES,
        "unstake": UNSTAKE_MESSAGES,
        "wallet_selector_stake": WALLET_SELECTOR_STAKE_MESSAGES,
        "delegate_required": DELEGATE_REQUIRED_MESSAGES,
        "delegation_confirming": DELEGATION_CONFIRMING_MESSAGES,
        "delegation_confirmed": DELEGATION_CONFIRMED_MESSAGES,
    }

    messages = messages_map.get(context, ["🥖 Let's bake some bread!"])
    return secrets.choice(messages)
